// Builds the site's image set from the legacy lintendant.com export.
//
//   npm run images            only (re)builds renditions that are missing
//   npm run images -- --force rebuilds everything
//   IMAGES_SRC=<dir> npm run images   reads the export from another folder
//
// For every photo it writes responsive WebP renditions to public/img
// (<slug>-<width>.webp, never upscaled), then records the source size and a
// tiny blurred placeholder in src/data/images.generated.js, which the page
// renderer uses for width/height (no layout shift) and the blur-up effect.
// It also writes public/favicon.svg and the social share image public/og.jpg.

import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"
import { PROJECTS } from "../src/data/projects.js"
import { HERO_SLUGS } from "../src/data/site.js"
import { MARK_SVG, wordmark } from "../src/render/brand.js"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const SRC = resolve(
  process.env.IMAGES_SRC || join(ROOT, "../Risk Management full-stack/src/assets/Origin Lintendant"),
)
const OUT = join(ROOT, "public/img")
const META = join(ROOT, "src/data/images.generated.js")
const FORCE = process.argv.includes("--force")

const W_PROJECT = [480, 960, 1600]
const W_HERO = [960, 1600, 1920, 2560]
const W_PANORAMA = [960, 1600, 2200]
const W_PORTRAIT = [480, 768]

// Index every file of the export by its NFC name. Names saved from the web
// are often NFD on disk ("é" as "e" + combining accent), so a direct join
// with the NFC names in projects.js would miss them.
const index = new Map()
for (const dir of readdirSync(SRC)) {
  const full = join(SRC, dir)
  if (!statSync(full).isDirectory()) continue
  for (const name of readdirSync(full)) index.set(name.normalize("NFC"), join(full, name))
}

function locate(file) {
  const found = index.get(file.normalize("NFC"))
  if (!found) throw new Error(`Image not found in ${SRC}: ${file}`)
  return found
}

const jobs = [
  ...PROJECTS.map((p) => ({ slug: p.slug, file: p.file, widths: HERO_SLUGS.includes(p.slug) ? W_HERO : W_PROJECT })),
  { slug: "entete-approche", file: "entete-approche.jpg", widths: W_PANORAMA },
  { slug: "entete-propos", file: "entete-propos.jpg", widths: W_PANORAMA },
  { slug: "entete-service", file: "entete-service.jpg", widths: W_PANORAMA },
  { slug: "construction-man", file: "construction-man.jpg", widths: W_PORTRAIT },
]

mkdirSync(OUT, { recursive: true })
const meta = {}
let written = 0

for (const job of jobs) {
  const input = locate(job.file)
  const source = sharp(input, { limitInputPixels: false }).rotate()
  const { width, height } = await source.metadata().then((m) =>
    // EXIF orientations 5–8 swap the axes once rotated.
    (m.orientation ?? 1) >= 5 ? { width: m.height, height: m.width } : m,
  )

  const widths = [...new Set([...job.widths.filter((w) => w < width), Math.min(width, Math.max(...job.widths))])]
  for (const w of widths) {
    const out = join(OUT, `${job.slug}-${w}.webp`)
    if (!FORCE && existsSync(out)) continue
    await source.clone().resize({ width: w }).webp({ quality: 74, effort: 5 }).toFile(out)
    written++
  }

  const lqip = await source.clone().resize({ width: 24 }).webp({ quality: 40 }).toBuffer()
  meta[job.slug] = { w: width, h: height, widths, lqip: `data:image/webp;base64,${lqip.toString("base64")}` }
  process.stdout.write(".")
}

writeFileSync(
  META,
  "// Generated by scripts/build-images.mjs — do not edit.\n" +
    `export default ${JSON.stringify(meta, null, 1)}\n`,
)

// Favicon: the square L' mark.
writeFileSync(join(ROOT, "public/favicon.svg"), MARK_SVG)

// Share image (1200x630): hero photo under a navy wash, with the wordmark.
const ogOverlay = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="#00213d" stop-opacity=".94"/><stop offset=".62" stop-color="#003865" stop-opacity=".55"/><stop offset="1" stop-color="#003865" stop-opacity=".15"/></linearGradient></defs>
    <rect width="1200" height="630" fill="url(#g)"/>
    <g transform="translate(16 262) scale(2.6)">${wordmark({ color: "#ffffff" }).replace(/^<svg[^>]*>|<\/svg>$/g, "").replace("<g ", '<g fill="#ffffff" ')}</g>
  </svg>`,
)
await sharp(locate(PROJECTS.find((p) => p.slug === HERO_SLUGS[0]).file), { limitInputPixels: false })
  .rotate()
  .resize(1200, 630, { fit: "cover" })
  .composite([{ input: ogOverlay }])
  .jpeg({ quality: 82, mozjpeg: true })
  .toFile(join(ROOT, "public/og.jpg"))

console.log(`\n${jobs.length} images, ${written} renditions written to public/img`)
